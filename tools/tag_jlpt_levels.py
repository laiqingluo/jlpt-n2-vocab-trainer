def build_level_map() -> dict[str, int]:
    """冲突时取更难的等级（数字更小 = 更难）。"""
    level_map: dict[str, int] = {}
    for level, word_set in [(5, N5), (4, N4), (3, N3)]:
        for word in word_set:
            # min = 取更难的
            level_map[word] = min(level_map.get(word, level), level)
    return level_map


def freq_fallback(count: int, is_n2_core: int) -> int:
    """频率兜底：保守估计（错杀不错放）。"""
    if is_n2_core:
        return 2
    if count >= 150:
        return 3   # 极高频 → 至少 N3
    if count >= 40:
        return 2   # 中频 → N2
    return 2       # 低频 → N2（保守）


def main() -> None:
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row

    # 确保列存在
    existing_cols = {row[1] for row in conn.execute("PRAGMA table_info(words)").fetchall()}
    if "jlpt_level" not in existing_cols:
        conn.execute("ALTER TABLE words ADD COLUMN jlpt_level INTEGER")

    level_map = build_level_map()
    words = conn.execute("SELECT id, word, count, is_n2_core FROM words").fetchall()

    updates: list[tuple[int, int]] = []
    stats: dict[int, int] = {5: 0, 4: 0, 3: 0, 2: 0, 1: 0}
    mapped = 0

    for row in words:
        word = row["word"]
        if word in level_map:
            level = level_map[word]
            mapped += 1
        else:
            level = freq_fallback(int(row["count"] or 0), int(row["is_n2_core"] or 0))
        stats[level] = stats.get(level, 0) + 1
        updates.append((level, row["id"]))

    conn.executemany("UPDATE words SET jlpt_level = ? WHERE id = ?", updates)
    conn.commit()
    conn.close()

    total = len(updates)
    print(f"完成！共处理 {total} 个词")
    print(f"词表匹配: {mapped} 个 | 频率兜底: {total - mapped} 个\n")
    for lv in [5, 4, 3, 2, 1]:
        bar = "█" * (stats.get(lv, 0) // 20)
        print(f"  N{lv}: {stats.get(lv, 0):5d}  {bar}")


if __name__ == "__main__":
    main()
