TARGET_POS = {
    '動詞','他五','自五','他下一','自下一','他上一','自上一',
    '自·他五','自他五','名·他サ','名·自サ','名·自他サ',
    '副詞','副','形状詞','ナ形','名·ナ形'
}

EXCLUDE_POS = {'感動詞', '接続詞', '連体詞', '接頭詞', '接尾詞'}

def pos_match(pos_str: str) -> bool:
    if pos_str in EXCLUDE_POS:
        return False
    for p in TARGET_POS:
        if p in pos_str:
            return True
    return False

def main():
    rows = []
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames
        rows = list(reader)

    updated = 0
    skipped_no_dict = []

    for row in rows:
        try:
            count = int(row.get("count", 0))
        except (ValueError, TypeError):
            count = 0

        if (
            pos_match(row.get("pos", ""))
            and not row.get("collocation", "").strip()
            and count >= 10
        ):
            word = row["word"]
            if word in COLLOCATIONS:
                row["collocation"] = COLLOCATIONS[word]
                updated += 1
            else:
                skipped_no_dict.append(word)

    # 备份
    backup = CSV_PATH.with_suffix(f".task1-backup.csv")
    shutil.copy(CSV_PATH, backup)

    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        fieldnames = csv.DictReader(f).fieldnames

    with open(CSV_PATH, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print("[OK] Task 1 done")
    print(f"  filled collocation: {updated}")
    print(f"  skipped (not in dict): {len(skipped_no_dict)}")
    if skipped_no_dict:
        print(f"  skipped words: {skipped_no_dict}")

    print("\n-- Top 10 results --")
    shown = 0
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            if row.get("collocation", "").strip() and shown < 10:
                print(f"  [{row['word']}] {row['collocation']}")
                shown += 1

if __name__ == "__main__":
    main()
